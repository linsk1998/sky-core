"use strict";

var fs = require("fs");
var path = require("path");
var rollup = require("rollup");
var createConfigs = require("../corejs/createConfigs");

/** 虚拟入口：entry 只存在于内存中，相对导入按它所在的目录解析 */
function virtualEntryPlugin(entryId, code) {
	return {
		name: "sky-virtual-entry",
		resolveId: function(id) {
			if(id === entryId) { return entryId; }
		},
		load: function(id) {
			if(id === entryId) { return code; }
		}
	};
}

/**
 * 生成虚拟入口代码：qunit-helpers + 选中的测试文件。
 * 相对导入基于虚拟入口实际所在目录（tests/corejs/local/）计算。
 */
function createEntryCode(root, files, entryId) {
	var entryDir = path.dirname(entryId);
	var lines = ["// virtual entry (generated by tests/lib/build-tests.js)"];
	var helpers = path.relative(entryDir, path.join(root, "tests/corejs/helpers/qunit-helpers.js")).replace(/\\/g, "/");
	lines.push("import " + JSON.stringify("./" + helpers) + ";");
	files.forEach(function(rel) {
		var fromEntry = path.relative(entryDir, path.join(root, rel)).replace(/\\/g, "/");
		lines.push("import " + JSON.stringify("./" + fromEntry) + ";");
	});
	return lines.join("\n") + "\n";
}

function entryIdFor(root, tier) {
	// 放在 tests/corejs/ 下，保证与 babel include（tests/corejs/**/*）兼容
	return path.join(root, "tests", "corejs", "local", "entry-" + tier + ".js");
}

/**
 * 纯 node 测试构建：不落盘，返回产物字符串。无 tier——注入配置来自
 * tests/impl-inject.js（直接映射到 impl/ 算法实现）。
 * 跳过 babel —— node 原生支持新语法，产物直接可执行。
 */
async function buildNodeBundle(files) {
	var root = process.cwd();
	var entryId = path.join(root, "tests", "corejs", "local", "entry-node.js");
	var config = createConfigs.createConfig("modern", {
		entry: entryId,
		babel: false,
		plugins: [virtualEntryPlugin(entryId, createEntryCode(root, files, entryId))]
	});
	// 替换 conditional-modern 为 impl-inject（纯算法不需要 tier 劫持）
	var injectIndex = config.inputOptions.plugins.findIndex(function(p) {
		return p && p.name === "polyfill-inject";
	});
	if(injectIndex >= 0) {
		config.inputOptions.plugins.splice.apply(
			config.inputOptions.plugins,
			[injectIndex, 1].concat(require("../impl-inject"))
		);
	}
	var bundle = await rollup.rollup(config.inputOptions);
	try {
		var generated = await bundle.generate(config.outputOptions);
		return generated.output[0].code;
	} finally {
		if(bundle.close) { await bundle.close(); }
	}
}

/**
 * 本机浏览器测试构建：只产内存字符串（{ compat, modern, es2015 }），
 * 不写任何文件；由 local-test-runner 插件的 loadHtml / configureServer
 * 直接对外服务。插件链（含 babel）与 npm run test:corejs 完全相同。
 */
async function buildLocalBundlesInMemory(tiers, files) {
	var root = process.cwd();
	var bundles = {};
	for(var i = 0; i < tiers.length; i++) {
		var tier = tiers[i];
		var entryId = entryIdFor(root, tier);
		var config = createConfigs.createConfig(tier, {
			entry: entryId,
			plugins: [virtualEntryPlugin(entryId, createEntryCode(root, files, entryId))]
		});
		var bundle = await rollup.rollup(config.inputOptions);
		try {
			var generated = await bundle.generate(config.outputOptions);
			bundles[tier] = generated.output[0].code;
		} finally {
			if(bundle.close) { await bundle.close(); }
		}
	}
	return bundles;
}

exports.virtualEntryPlugin = virtualEntryPlugin;
exports.createEntryCode = createEntryCode;
exports.buildNodeBundle = buildNodeBundle;
exports.buildLocalBundlesInMemory = buildLocalBundlesInMemory;
